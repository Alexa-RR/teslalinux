#!/usr/bin/env python3
"""conscrypt-aconfig.py: the Java flag classes Soong's java_aconfig_library generates from an
.aconfig file, for the build-dist.sh conscrypt step (no Soong/aconfig tool here).

  conscrypt-aconfig.py DECLARATIONS.aconfig OUTDIR [NAME=true|false ...]

AOSP builds Conscrypt with `conscrypt-aconfig-flags-lib` (Android.bp): the package's Flags,
FeatureFlags and FeatureFlagsImpl classes, whose values come from the release configuration the
platform is built for. Every Conscrypt flag is `is_fixed_read_only`, so the generated accessors
return a constant fixed at build time; a flag the release configuration gives no value is
DISABLED (aconfig's default). The Android 15 release configurations (build/release at
android-15.0.0_r36: ap4a, bp1a) set none of com.android.org.conscrypt.flags, so all are false;
NAME=VALUE overrides one. A flag that is not fixed read-only would need the device's flag
storage, which this runtime does not have: refused.
"""
import os
import re
import sys


def parse(text):
    """(package, [(name, description, fixed_read_only)]) from aconfig's text proto"""
    text = re.sub(r"#[^\n]*", "", text)
    m = re.search(r'^\s*package:\s*"([^"]+)"', text, re.M)
    if not m:
        sys.exit("no package in declarations")
    flags = []
    for body in re.findall(r"flag\s*\{(.*?)\n\}", text, re.S):
        name = re.search(r'name:\s*"([^"]+)"', body).group(1)
        desc = re.search(r'description:\s*"([^"]*)"', body)
        fixed = re.search(r"is_fixed_read_only:\s*true", body) is not None
        flags.append((name, desc.group(1) if desc else "", fixed))
    return m.group(1), flags


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    decl, out = sys.argv[1], sys.argv[2]
    values = {}
    for a in sys.argv[3:]:
        k, _, v = a.partition("=")
        if v not in ("true", "false"):
            sys.exit("value for %s must be true or false" % k)
        values[k] = v == "true"
    with open(decl, encoding="utf-8") as f:
        package, flags = parse(f.read())
    unknown = set(values) - {n for n, _, _ in flags}
    if unknown:
        sys.exit("no such flag: " + ", ".join(sorted(unknown)))
    for name, _, fixed in flags:
        if not fixed:
            sys.exit("flag %s is not fixed read-only: its value would come from device flag storage" % name)

    d = os.path.join(out, *package.split("."))
    os.makedirs(d, exist_ok=True)
    hdr = "package %s;\n\n// Generated by tools/debvm/patches/conscrypt-aconfig.py from %s.\n" % (
        package, os.path.basename(decl))

    s = [hdr, "/** @hide */\npublic final class Flags {\n"]
    for name, _, _ in flags:
        s.append('    /** @hide */\n    public static final String FLAG_%s = "%s.%s";\n' % (name.upper(), package, name))
    for name, desc, _ in flags:
        s.append("\n    /** %s */\n    public static boolean %s() {\n        return FEATURE_FLAGS.%s();\n    }\n"
                 % (desc.replace("*/", "* /"), camel(name), camel(name)))
    s.append("\n    private static FeatureFlags FEATURE_FLAGS = new FeatureFlagsImpl();\n}\n")
    write(os.path.join(d, "Flags.java"), "".join(s))

    s = [hdr, "/** @hide */\npublic interface FeatureFlags {\n"]
    for name, _, _ in flags:
        s.append("    boolean %s();\n" % camel(name))
    s.append("}\n")
    write(os.path.join(d, "FeatureFlags.java"), "".join(s))

    s = [hdr, "/** @hide */\npublic final class FeatureFlagsImpl implements FeatureFlags {\n"]
    for name, _, _ in flags:
        s.append("    @Override\n    public boolean %s() {\n        return %s;\n    }\n"
                 % (camel(name), "true" if values.get(name, False) else "false"))
    s.append("}\n")
    write(os.path.join(d, "FeatureFlagsImpl.java"), "".join(s))
    for name, _, _ in flags:
        print("%s.%s = %s" % (package, name, "true" if values.get(name, False) else "false"))


def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
